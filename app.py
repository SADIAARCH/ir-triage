"""Streamlit live dashboard:  streamlit run app.py"""
import time

import pandas as pd
import streamlit as st

from triage.config import ESCALATE_CONFIDENCE
from triage.pipeline import TriagePipeline
from triage.sources import simulate, tail

st.set_page_config(page_title="IR Triage Agent", layout="wide")
st.title("Real-Time Network Forensics & Incident Triage")
st.caption("Decider 2B triages every line in milliseconds. Bedrock only wakes up for confirmed exploits.")

COLORS = {"BENIGN": "#1b5e20", "SUSPICIOUS_PROBE": "#b26a00",
          "ACTIVE_EXPLOIT": "#c62828", "CRITICAL_INTRUSION": "#6a1b9a"}

with st.sidebar:
    mode = st.radio("Log source", ["Simulated attack", "Tail a log file"])
    path = st.text_input("Log file path", "/var/log/nginx/access.log") if mode != "Simulated attack" else None
    rate = st.slider("Lines per second", 1, 30, 8)
    max_lines = st.number_input("Stop after N lines", 50, 5000, 600)
    run = st.button("Start stream", type="primary")
    st.write(f"Escalation threshold: confidence > **{ESCALATE_CONFIDENCE}**")

if "pipe" not in st.session_state:
    st.session_state.pipe = TriagePipeline()
    st.session_state.reports = []
pipe = st.session_state.pipe

c1, c2, c3, c4, c5 = st.columns(5)
m_total, m_lat, m_probe, m_exploit, m_bedrock = c1.empty(), c2.empty(), c3.empty(), c4.empty(), c5.empty()
left, right = st.columns([3, 2])
table_slot = left.empty()
right.subheader("Bedrock incident reports")
reports_slot = right.container()
rows = []


def style_row(row):
    return [f"background-color: {COLORS.get(row['verdict'], '#222')}; color: white"] * len(row)


def render_metrics():
    total = sum(pipe.counts.values())
    m_total.metric("Lines triaged", total)
    m_lat.metric("Avg decision latency", f"{pipe.avg_latency_ms:.0f} ms")
    m_probe.metric("Probes", pipe.counts["SUSPICIOUS_PROBE"])
    m_exploit.metric("Exploits / intrusions",
                     pipe.counts["ACTIVE_EXPLOIT"] + pipe.counts["CRITICAL_INTRUSION"])
    m_bedrock.metric("Bedrock calls", len(st.session_state.reports) + len(pipe.futures))
    with reports_slot:
        pass


def render_reports():
    reports_slot.empty()
    with reports_slot:
        if pipe.futures:
            st.info(f"{len(pipe.futures)} report(s) being generated by Bedrock...")
        for r in reversed(st.session_state.reports):
            with st.expander(f"{r.ip} — generated in {r.seconds:.1f}s", expanded=(r is st.session_state.reports[-1])):
                st.markdown(r.text)


render_metrics()
render_reports()

if run:
    source = simulate(rate) if mode == "Simulated attack" else tail(path)
    for i, line in enumerate(source):
        if i >= max_lines:
            break
        e = pipe.process(line)
        rows.append({"time": time.strftime("%H:%M:%S", time.localtime(e.ts)),
                     "verdict": e.verdict.label, "conf": round(e.verdict.confidence, 2),
                     "action": e.action, "line": e.line[:110]})
        st.session_state.reports += pipe.collect_reports()
        table_slot.dataframe(pd.DataFrame(rows[-18:][::-1]).style.apply(style_row, axis=1),
                             use_container_width=True, hide_index=True)
        render_metrics()
        if i % 5 == 0 or pipe.futures:
            render_reports()
    # drain pending reports
    deadline = time.time() + 60
    while pipe.futures and time.time() < deadline:
        time.sleep(0.5)
        st.session_state.reports += pipe.collect_reports()
    render_metrics()
    render_reports()
